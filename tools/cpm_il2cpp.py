#!/usr/bin/env python3
"""Turn the game's IL2CPP `dump.cs` into the layout tables this tweak ships with.

    python3 tools/cpm_il2cpp.py generate     # regenerate the derived files
    python3 tools/cpm_il2cpp.py check        # fail if the committed files drifted from dump.cs
    python3 tools/cpm_il2cpp.py show         # print the extracted manifest as JSON
    python3 tools/cpm_il2cpp.py selftest     # assert known facts about the checked-in dump

Why this exists
---------------
Car Parking Multiplayer is a Unity IL2CPP build.  Everything the automation needs
(which class holds the vinyl editor, where the sticker list lives inside it, what the
`VinylsType` values are, how big a `StickerItem` layer record is) is *not* guessable -
it moves with every game update.  Il2CppDumper's `dump.cs` has all of it, but reading a
730k-line text file at runtime is not an option, so this tool extracts the subset named
in `tools/cpm_layout_spec.json` and emits:

    Resources/cpm_il2cpp_layout.json   machine readable, bundled with the dylib
    Core/CPMGameLayout.h               offsets + enums the Objective-C code compiles against
    Core/CPMGameLayout.m               lookup tables + staleness reporting

Fields whose offset the dump cannot know (generic type definitions such as List`1 are
emitted with 0x0 by Il2CppDumper) are marked "runtimeOnly"; CPMGameLayout.h gives them
CPMGameOffsetRuntimeOnly and the bridge resolves them from the live binary instead.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC_PATH = ROOT / "tools" / "cpm_layout_spec.json"
GENERATED_MARK = "generated by tools/cpm_il2cpp.py - DO NOT EDIT"

IMAGE_RE = re.compile(r"^// Image (\d+): (.+?) - \d+\s*$")
NS_RE = re.compile(r"^// Namespace: (?:(?P<ns>.*?) - )?(?P<asm>\S+)\s*$")
IMG_LINE_RE = re.compile(r"^// Image: (?P<asm>\S+)\s*$")
TYPE_RE = re.compile(
    r"^(?P<mods>(?:(?:public|private|protected|internal|abstract|sealed|static|readonly|beforefieldinit)\s+)*)"
    r"(?P<kind>class|struct|enum|interface)\s+(?P<name>[^\s:{]+)"
    r"(?:\s*:\s*(?P<base>[^{]+?))?\s*(?://\s*TypeDefIndex:\s*(?P<tdi>\d+))?\s*$"
)
FIELD_RE = re.compile(
    r"^\s*(?P<mods>(?:(?:public|private|protected|internal|static|readonly|const|volatile)\s+)*)"
    r"(?P<type>[^;=]+?)\s+(?P<name><\w+>k__BackingField|\w+)\s*"
    r"(?:=\s*(?P<cval>[^;]+?))?\s*;\s*(?://\s*(?P<off>0x[0-9A-Fa-f]+))?\s*$"
)
METHOD_RE = re.compile(
    r"^\s*(?P<mods>(?:(?:public|private|protected|internal|static|virtual|override|abstract|sealed|extern|hidebysig|new)\s+)*)"
    r"(?P<ret>[^(]+?)\s+(?P<name>\.ctor|\.cctor|<[^>]+>b__\w+|\w+(?:\.\w+)*)\s*"
    r"\((?P<params>[^)]*)\)\s*(?:where [^{]*)?\{\s*\}\s*$"
)
RVA_RE = re.compile(r"^// RVA: (?P<rva>0x[0-9A-F]+)\s+Offset: (?P<off>0x[0-9A-F]+)\s+VA: (?P<va>0x[0-9A-F]+)")
ENUM_MEMBER_RE = re.compile(r"^\s*(?P<name>\w+)\s*=\s*(?P<value>-?0x[0-9A-Fa-f]+|-?\d+)u?[,;]?\s*$")
SECTION_RE = re.compile(r"^//\s*(Fields|Properties|Methods|Constructors)\s*$")

TYPE_KINDS = [
    (r"^bool$", ("bool", 1)),
    (r"^byte$|^System\.Byte$", ("u8", 1)),
    (r"^sbyte$|^System\.SByte$", ("i8", 1)),
    (r"^char$|^System\.Char$", ("char", 2)),
    (r"^short$|^System\.Int16$", ("i16", 2)),
    (r"^ushort$|^System\.UInt16$", ("u16", 2)),
    (r"^int$|^System\.Int32$|^System\.UInt32$|^uint$", ("i32", 4)),
    (r"^long$|^System\.Int64$|^ulong$|^System\.UInt64$|^IntPtr$|^System\.UIntPtr$", ("i64", 8)),
    (r"^float$|^System\.Single$", ("f32", 4)),
    (r"^double$|^System\.Double$", ("f64", 8)),
    (r"Vector2$|^UnityEngine\.Vector2$", ("vec2", 8)),
    (r"Vector3$|^UnityEngine\.Vector3$", ("vec3", 12)),
    (r"Vector4$|^UnityEngine\.Vector4$|^Quaternion$", ("vec4", 16)),
    (r"Color$|^UnityEngine\.Color32$", ("color", 16)),
    (r"Color32$", ("color", 4)),
    (r"Bounds$|^UnityEngine\.Bounds", ("bounds", 24)),
    (r"^\s*(public |private |internal )*string\b", ("string", 8)),
]


def classify(typ: str) -> tuple[str, int]:
    """Map a dump type name onto (kind, size) as the runtime reader needs it."""
    t = typ.strip()
    t = re.sub(r"\s*\{\s*get.*$", "", t)
    for pat, out in TYPE_KINDS:
        if re.search(pat, t):
            return out
    if t.endswith("*") or t.endswith("[]"):
        return ("ptr", 8)
    if re.match(r"^[A-Z]", t) and "." in t or t[:1].isupper():
        # anything that looks like a managed reference (class/interface/array/Nullable<>)
        if "<" in t and not t.startswith("System.Nullable"):
            return ("object", 8)
        return ("object", 8)
    return ("unknown", 0)


def clean_type(t: str) -> str:
    t = t.strip()
    t = re.sub(r"\s+", " ", t)
    return t


class Dump:
    """Streaming parser for Il2CppDumper's dump.cs."""

    def __init__(self, path: Path):
        self.path = path
        self.images: list[str] = []
        self.types: dict[str, dict] = {}          # "ns.Name" -> record (first match wins)
        self.all_types: dict[str, list[dict]] = {}  # "ns.Name" -> every match (name collisions across images)
        self.enum_values: dict[str, dict[str, int]] = {}
        self.enum_size: dict[str, int] = {}   # bare + dotted name -> field size in bytes
        self.type_count = 0
        self.parse()

    # -- parsing ---------------------------------------------------------
    def parse(self) -> None:
        cur: dict | None = None
        section = ""
        ns, asm = "", ""
        pending_rva: dict | None = None
        in_body = False
        depth = 0

        with self.path.open("r", encoding="utf-8", errors="replace") as fh:
            for raw in fh:
                line = raw.rstrip("\n")

                m = IMAGE_RE.match(line)
                if m and not in_body:
                    self.images.append(m.group(2))
                    continue
                if line.startswith("// Namespace:") or line.startswith("// Image:"):
                    ns, asm = "", ""
                    mm = NS_RE.match(line)
                    if mm:
                        ns = (mm.group("ns") or "").strip()
                        asm = mm.group("asm").strip()
                        continue
                    mm = IMG_LINE_RE.match(line)
                    if mm:
                        asm = mm.group("asm").strip()
                        ns = ""
                        continue
                    continue

                if not in_body:
                    mt = TYPE_RE.match(line)
                    if mt and mt.group("kind") in ("class", "struct", "enum", "interface"):
                        name = mt.group("name").strip()
                        kind = mt.group("kind")
                        full = f"{ns}.{name}" if ns else name
                        cur = {
                            "name": name,
                            "namespace": ns,
                            "assembly": asm,
                            "kind": kind,
                            "base": (mt.group("base") or "").strip().rstrip("{").strip(),
                            "typedefIndex": int(mt.group("tdi")) if mt.group("tdi") else None,
                            "fields": {},
                            "staticFields": {},
                            "methods": {},
                            "properties": {},
                            "enumValues": {},
                        }
                        section = ""
                        pending_rva = None
                        in_body = True
                        depth = 0
                    continue

                # inside a type body
                stripped = line.strip()
                if stripped == "{":
                    depth += 1
                    continue
                if stripped == "}":
                    depth -= 1
                    if depth <= 0:
                        assert cur is not None
                        self.add(cur)
                        cur = None
                        in_body = False
                    continue

                if cur is None:
                    continue

                ms = SECTION_RE.match(stripped)
                if ms:
                    section = ms.group(1)
                    continue
                mr = RVA_RE.match(stripped)
                if mr:
                    pending_rva = {k: int(v, 16) for k, v in mr.groupdict().items()}
                    continue

                if section in ("Fields", "Properties", ""):
                    mf = FIELD_RE.match(line)
                    if mf:
                        self.add_field(cur, mf)
                        continue
                if section in ("Methods", "Constructors", ""):
                    mmth = METHOD_RE.match(line)
                    if mmth:
                        self.add_method(cur, mmth, pending_rva)
                        pending_rva = None
                        continue
                if cur["kind"] == "enum":
                    me = ENUM_MEMBER_RE.match(line)
                    if me:
                        v = me.group("value")
                        cur["enumValues"][me.group("name")] = int(v, 0)
                        continue

    def add_field(self, cur: dict, mf: re.Match) -> None:
        mods = mf.group("mods") or ""
        typ = clean_type(mf.group("type"))
        name = mf.group("name")
        off_txt = mf.group("off")
        off = int(off_txt, 16) if off_txt else None
        is_static = "static" in mods
        is_const = "const" in mods
        if is_const:
            return
        kind, size = classify(typ)
        rec = {
            "type": typ,
            "offset": off,
            "size": size,
            "kind": kind,
            "static": is_static,
            "readonly": "readonly" in mods,
            "access": ("public" if "public" in mods else
                       "private" if "private" in mods else
                       "protected" if "protected" in mods else "internal"),
        }
        # Generic type *definitions* are dumped with 0x0 offsets: the real layout only
        # exists once the runtime instantiates List<T>/Dictionary<K,V>.
        if not is_static and (off is None or off == 0):
            rec["offset"] = None
            rec["runtimeOnly"] = True
        if is_static and "k__BackingField" in name:
            rec["runtimeOnly"] = False
        bucket = cur["staticFields"] if is_static else cur["fields"]
        bucket[name] = rec

    def add_method(self, cur: dict, mmth: re.Match, rva: dict | None) -> None:
        mods = mmth.group("mods") or ""
        name = mmth.group("name")
        params = clean_type(mmth.group("params") or "")
        params = re.sub(r"\s*,\s*", ", ", params)
        rec = {
            "return": clean_type(mmth.group("ret")),
            "params": params,
            "static": "static" in mods,
            "access": ("public" if "public" in mods else
                       "private" if "private" in mods else
                       "protected" if "protected" in mods else "internal"),
        }
        if rva:
            rec["rva"] = rva["rva"]
            rec["va"] = rva["va"]
        key = name
        if params:
            arity = len([p for p in params.split(",") if p.strip()])
            key = f"{name}/{arity}"
        cur["methods"][key] = rec
        cur["methods"].setdefault(name, rec)

    def add(self, cur: dict) -> None:
        self.type_count += 1
        if cur["kind"] == "enum":
            size = {"byte": 1, "sbyte": 1, "short": 2, "ushort": 2,
                    "uint": 4, "int": 4, "long": 8, "ulong": 8}.get(cur["base"], 4)
            full = f"{cur['namespace']}.{cur['name']}" if cur["namespace"] else cur["name"]
            for key in (full, cur["name"]):
                self.enum_size.setdefault(key, size)
        full = f"{cur['namespace']}.{cur['name']}" if cur["namespace"] else cur["name"]
        self.all_types.setdefault(full, []).append(cur)
        # First definition wins unless a later one carries an explicit namespace for a
        # name the spec asked for without one (e.g. global-namespace StickerItem).
        self.types.setdefault(full, cur)
        if cur["kind"] == "enum":
            self.enum_values.setdefault(full, cur["enumValues"])

    # -- lookups ---------------------------------------------------------
    def find(self, dotted: str) -> dict | None:
        """Look a type up by `namespace.Name` (or bare name).

        Unity/NGUI ship several assemblies that define the *same* dotted type name
        (UnityEngine.Object exists in UnityEngine.dll as a stub and in
        UnityEngine.CoreModule.dll with the real fields), so every match is merged:
        a field is taken from whichever definition actually declares it.
        """
        matches = self.find_all(dotted)
        if not matches:
            return None
        if len(matches) == 1:
            return matches[0]
        best = max(matches, key=lambda r: len(r["fields"]) + len(r["methods"]))
        merged = dict(best)
        for key in ("fields", "staticFields", "methods", "properties", "enumValues"):
            union: dict = {}
            for rec in matches:
                for name, val in rec.get(key, {}).items():
                    union.setdefault(name, val)
            merged[key] = union
        return merged

    def find_all(self, dotted: str) -> list[dict]:
        bare = dotted.split(".")[-1]
        out = []
        for key, lst in self.all_types.items():
            if key == dotted or key.split(".")[-1] == bare:
                out.extend(lst)
        return out


def select(names: list[str], available: dict) -> tuple[dict, list[str], list[str]]:
    """Apply a spec selector list to a {name: rec} mapping."""
    wanted: dict = {}
    missing: list[str] = []
    if names == ["*"]:
        return dict(available), [], []
    excludes = {n[1:] for n in names if n.startswith("!")}
    for want in names:
        if want.startswith("!"):
            continue
        if want in available and want not in excludes:
            wanted[want] = available[want]
        else:
            missing.append(want)
    return wanted, missing, sorted(excludes)


def build_manifest(dump: Dump, spec: dict) -> tuple[dict, list[str], list[str]]:
    errors: list[str] = []
    warnings: list[str] = []
    classes: dict[str, dict] = {}

    for want in spec.get("classes", []):
        optional = bool(want.get("optional"))
        dotted = want["name"]
        if want.get("namespace") == "" and "." in dotted:
            dotted = dotted.split(".")[-1]
        rec = dump.find(dotted)
        if rec is None:
            msg = f"class not found in dump.cs: {dotted}"
            (warnings if optional else errors).append(msg)
            continue
        every_field = dict(rec["fields"])
        every_field.update(rec["staticFields"])
        selected, miss_f, _ = select(want.get("fields", []), every_field)
        fields = {k: v for k, v in selected.items() if k in rec["fields"]}
        statics = {k: v for k, v in selected.items() if k in rec["staticFields"]}
        methods, miss_m, _ = select(want.get("methods", []), rec["methods"])
        missed = sorted(set(miss_f))
        if missed and want.get("fields") != ["*"]:
            msg = f"{dotted}: fields not in dump: {', '.join(missed)}"
            (warnings if optional else errors).append(msg)
        miss_m = [m for m in miss_m if "/" not in m]
        if miss_m and want.get("methods") != ["*"]:
            msg = f"{dotted}: methods not in dump: {', '.join(sorted(miss_m))}"
            (warnings if optional else errors).append(msg)

        def fix_enum(fdata: dict) -> dict:
            bare = re.sub(r"<.*$", "", (fdata.get("type") or "")).strip().split(".")[-1]
            size = dump.enum_size.get(bare)
            if size and fdata.get("kind") in ("object", "unknown"):
                fdata = dict(fdata)
                fdata["kind"] = "u8" if size == 1 else ("u16" if size == 2 else "i32")
                fdata["size"] = size
                fdata["enum"] = True
            return fdata

        fields = {k: fix_enum(v) for k, v in fields.items()}
        statics = {k: fix_enum(v) for k, v in statics.items()}
        classes[want["id"]] = {
            "className": rec["name"],
            "namespace": rec["namespace"],
            "assembly": rec["assembly"],
            "base": rec["base"],
            "typedefIndex": rec["typedefIndex"],
            "comment": want.get("comment", ""),
            "fields": {k: {kk: vv for kk, vv in v.items() if vv is not None} for k, v in fields.items()},
            "staticFields": {k: {kk: vv for kk, vv in v.items() if vv is not None} for k, v in statics.items()},
            "methods": {k: {kk: vv for kk, vv in v.items() if vv is not None}
                        for k, v in methods.items() if "/" not in k},
        }

    enums: dict[str, dict] = {}
    for want in spec.get("enums", []):
        dotted = want["name"]
        vals = dump.enum_values.get(dotted)
        if vals is None:
            rec = dump.find(dotted)
            vals = rec["enumValues"] if rec else None
        if not vals:
            msg = f"enum not found in dump.cs: {dotted}"
            (warnings if want.get("optional") else errors).append(msg)
            continue
        enums[want["id"]] = {
            "enumName": dotted.split(".")[-1],
            "namespace": dotted.rsplit(".", 1)[0] if "." in dotted else "",
            "values": vals,
        }

    return {"classes": classes, "enums": enums}, errors, warnings


def dump_identity(path: Path) -> dict:
    h = hashlib.sha256()
    size = 0
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
            size += len(chunk)
    return {"path": path.name, "bytes": size, "sha256": h.hexdigest(), "short": h.hexdigest()[:16]}


