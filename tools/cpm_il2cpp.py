def c_ident(*parts: str) -> str:
    out = ""
    for p in parts:
        # compiler-generated names: <Foo>k__BackingField -> Foo
        p = re.sub(r"^<(\w+)>k__BackingField$", r"\1", p)
        p = re.sub(r"[^0-9A-Za-z]+", "_", p).strip("_")
        if p:
            out += p[0].upper() + p[1:]
    return out


def emit_header(manifest: dict, ident: dict, meta: dict) -> str:
    L: list[str] = []
    a = L.append
    a("/**")
    a(f" * CPMGameLayout.h -- {GENERATED_MARK}.")
    a(" *")
    a(" * Field offsets, enum values and type names taken from the game's IL2CPP dump")
    a(f" * ({ident['path']}, sha256 {ident['short']}, {ident['bytes']} bytes,")
    a(f" *  {meta['images']} images / {meta['types']} types).")
    a(" *")
    a(" * Do not hand-edit: run `make layout` after re-dumping the game.")
    a(" */")
    a("#ifndef CPMGameLayout_h")
    a("#define CPMGameLayout_h")
    a("")
    a("#import <Foundation/Foundation.h>")
    a("")
    a("NS_ASSUME_NONNULL_BEGIN")
    a("")
    a(f"#define CPM_GAME_LAYOUT_DUMP_SHA256 @\"{ident['sha256']}\"")
    a(f"#define CPM_GAME_LAYOUT_DUMP_BYTES {ident['bytes']}")
    a(f"#define CPM_GAME_LAYOUT_TYPE_COUNT {meta['types']}")
    a(f"#define CPM_GAME_LAYOUT_IMAGE_COUNT {meta['images']}")
    a("#define CPM_GAME_LAYOUT_STICKER_ITEM_SIZE 0")
    a("")
    a("/// Offset the dump could not know (generic definition laid out at runtime).")
    a("static const uint32_t CPMGameOffsetRuntimeOnly = 0xFFFFFFFFu;")
    a("static const uint32_t CPMGameOffsetNone = 0xFFFFFFFEu;")
    a("")
    # class ids
    a("typedef NS_ENUM(NSInteger, CPMGameClassID) {")
    a("    CPMGameClassNone = -1,")
    for cid, rec in manifest["classes"].items():
        a(f"    CPMGameClass{c_ident(cid)},")
    a(f"    CPMGameClassCount = {len(manifest['classes'])},")
    a("};")
    a("")
    # field ids
    a("typedef NS_ENUM(NSInteger, CPMGameFieldID) {")
    a("    CPMGameFieldNone = -1,")
    fid = 0
    field_rows: list[tuple[int, int, str, str, str, bool, str, int]] = []
    for ci, (cid, rec) in enumerate(manifest["classes"].items()):
        for fname, fre in sorted(rec["fields"].items(), key=lambda kv: (kv[1].get("offset") is None, kv[1].get("offset") or 0, kv[0])):
            a(f"    CPMGameField{c_ident(cid, fname)} = {fid},")
            field_rows.append((ci, fid, cid, fname, fre.get("type", ""), False, fre.get("kind", "unknown"), int(fre.get("size", 0) or 0)))
            fid += 1
        for fname, fre in sorted(rec["staticFields"].items()):
            a(f"    CPMGameField{c_ident(cid, fname)} = {fid},")
            field_rows.append((ci, fid, cid, fname, fre.get("type", ""), True, fre.get("kind", "unknown"), int(fre.get("size", 0) or 0)))
            fid += 1
    a(f"    CPMGameFieldCount = {fid},")
    a("};")
    a("")
    # enums from the game
    for eid, erec in manifest["enums"].items():
        a(f"/// {erec['namespace']}.{erec['enumName']} (from the dump)")
        for name, value in sorted(erec["values"].items(), key=lambda kv: kv[1]):
            a(f"static const NSInteger CPMGameE{c_ident(eid, name)} = {value};")
        a("")
    a("typedef struct {")
    a("    CPMGameClassID cls;")
    a("    CPMGameFieldID field;")
    a("    uint32_t offset;      /* dump offset, or CPMGameOffsetRuntimeOnly */")
    a("    uint16_t size;        /* 0 = unknown */")
    a("    uint8_t kind;         /* CPMGameValueKind */")
    a("    uint8_t isStatic;")
    a("    const char *className;")
    a("    const char *fieldName;")
    a("    const char *typeName;")
    a("} CPMGameFieldRecord;")
    a("")
    a("typedef NS_ENUM(NSInteger, CPMGameValueKind) {")
    a("    CPMGameValueKindUnknown = 0,")
    a("    CPMGameValueKindBool = 1,")
    a("    CPMGameValueKindInt32 = 2,")
    a("    CPMGameValueKindInt64 = 3,")
    a("    CPMGameValueKindFloat = 4,")
    a("    CPMGameValueKindDouble = 5,")
    a("    CPMGameValueKindObject = 6,")
    a("    CPMGameValueKindString = 7,")
    a("    CPMGameValueKindVector2 = 8,")
    a("    CPMGameValueKindVector3 = 9,")
    a("    CPMGameValueKindVector4 = 10,")
    a("    CPMGameValueKindColor = 11,")
    a("    CPMGameValueKindUInt8 = 12,")
    a("};")
    a("")
    a("extern const CPMGameFieldRecord CPMGameFieldTable[CPMGameFieldCount];")
    a("")
    a("/// Number of entries in the generated tables.")
    a("NSInteger CPMGameLayoutClassCount(void);")
    a("NSInteger CPMGameLayoutFieldCount(void);")
    a("")
    a("/// Dump-relative offset for a field; CPMGameOffsetRuntimeOnly when the dump")
    a("/// cannot know it (generic definitions) and CPMGameOffsetNone when absent.")
    a("uint32_t CPMGameLayoutOffset(CPMGameClassID cls, CPMGameFieldID field);")
    a("")
    a("/// Name lookups (stable UTF-8, owned by the __TEXT segment).")
    a("const char *_Nullable CPMGameLayoutClassName(CPMGameClassID cls);")
    a("const char *_Nullable CPMGameLayoutClassNamespace(CPMGameClassID cls);")
    a("const char *_Nullable CPMGameLayoutClassAssembly(CPMGameClassID cls);")
    a("const char *_Nullable CPMGameLayoutFieldName(CPMGameFieldID field);")
    a("CPMGameClassID CPMGameLayoutClassForName(NSString *className);")
    a("CPMGameFieldID CPMGameLayoutFieldForName(CPMGameClassID cls, NSString *fieldName);")
    a("")
    a("/// Human readable one-liner for logs / the settings panel: dump hash + coverage.")
    a("NSString *CPMGameLayoutSignature(void);")
    a("")
    a("/// YES when every needed offset came from the dump (no runtime-only holes).")
    a("BOOL CPMGameLayoutIsSelfContained(void);")
    a("NSInteger CPMGameLayoutRuntimeOnlyFieldCount(void);")
    a("")
    a("NS_ASSUME_NONNULL_END")
    a("#endif /* CPMGameLayout_h */")
    return "\n".join(L) + "\n", field_rows


